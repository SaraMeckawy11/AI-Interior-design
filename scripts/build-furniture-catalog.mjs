/**
 * Inline the Livinai furniture catalogue (.glb) into modules the walkthrough
 * WebView can hand straight to GLTFLoader.
 *
 * The models are emitted verbatim — the exact bytes of the exact files
 * Livinai_web serves from `public/models`, decoded by the exact loader it uses.
 * Whatever a model contains (materials, textures, multiple meshes) survives.
 *
 * One module per model, not one module for the catalogue. `chair-modern.glb`
 * alone is 4.1 MB, so a single module meant every walkthrough — every *import*
 * of the walkthrough screen — pulled ~7 MB of base64 into the JS heap whether
 * the plan could draw it or not. Split, a plan loads only the handful of models
 * its rooms actually ask for, and only when the scene asks for them.
 *
 * Run:
 *
 *     node scripts/build-furniture-catalog.mjs
 */

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const MODELS_DIR = path.join(here, "..", "assets", "models");
const OUTPUT_DIR = path.join(here, "..", "lib", "furniture");
const INDEX = path.join(here, "..", "lib", "furnitureCatalog.js");

/**
 * Catalogue key -> file, copied verbatim from Livinai_web's `MODEL_PATHS` in
 * src/Plan3DScene.jsx. Keys are the `spec.model` values a room programme emits,
 * or the alias one is resolved through (see CATALOG_ALIAS in walkthroughScene).
 *
 * `workDesk` really does reuse the dining table — that is the web's own
 * mapping, not a substitution. `roundDiningTable` is deliberately null there,
 * so it has no entry here either.
 */
const CATALOG = {
  sofa: "sofa-modern.glb",
  compactSofa: "sofa-compact.glb",
  armchair: "armchair.glb",
  coffeeTable: "coffee-table.glb",
  diningTable: "dining-table.glb",
  diningChair: "dining-chair.glb",
  workDesk: "dining-table.glb",
  bed: "bed.glb",
  island: "kitchen-island.glb",
  fridge: "fridge.glb",
  vanity: "vanity.glb",
  toilet: "toilet.glb",
  shower: "shower.glb",
  bathtub: "bathtub.glb",
  tvUnit: "tv-unit.glb",
  bookcase: "bookcase.glb",
  modernChair: "chair-modern.glb",
};

fs.rmSync(OUTPUT_DIR, { recursive: true, force: true });
fs.mkdirSync(OUTPUT_DIR, { recursive: true });

const report = [];
for (const [key, file] of Object.entries(CATALOG)) {
  const source = path.join(MODELS_DIR, file);
  if (!fs.existsSync(source)) {
    console.warn(`skip ${key}: ${file} not found`);
    continue;
  }
  const bytes = fs.readFileSync(source);
  if (bytes.readUInt32LE(0) !== 0x46546c67) throw new Error(`${file} is not a binary glTF`);
  const base64 = bytes.toString("base64");
  fs.writeFileSync(
    path.join(OUTPUT_DIR, `${key}.js`),
    `// Generated from assets/models/${file} — do not edit by hand.\n`
    + `export default ${JSON.stringify(base64)};\n`,
    "utf8",
  );
  report.push({ key, file, kb: bytes.length / 1024, b64: base64.length / 1024 });
}

report.sort((one, two) => two.kb - one.kb);
report.forEach((row) => console.log(
  `${row.key.padEnd(14)} ${row.file.padEnd(20)} ${row.kb.toFixed(0).padStart(6)} KB -> ${row.b64.toFixed(0).padStart(6)} KB base64`,
));

const requires = report
  .map((row) => `  ${row.key}: () => require("./furniture/${row.key}").default,`)
  .join("\n");

const index = `/**
 * Generated by scripts/build-furniture-catalog.mjs — do not edit by hand.
 *
 * The Livinai furniture catalogue: the exact .glb files Livinai_web serves from
 * public/models, base64-encoded so the walkthrough WebView can parse them with
 * GLTFLoader without needing filesystem or network access. Bytes are untouched,
 * so meshes, materials and textures are identical to the web build.
 *
 * Keys mirror Livinai_web's MODEL_PATHS. Each model lives in its own module and
 * is required on demand, so a plan only ever materialises the models its rooms
 * can actually draw.
 */

const LOADERS = {
${requires}
};

/** Every catalogue key, in no particular order. */
export const FURNITURE_MODEL_KEYS = Object.keys(LOADERS);

/** Base64 .glb bytes for one model, or null when the key is unknown. */
export function loadFurnitureModel(key) {
  const loader = LOADERS[key];
  if (!loader) return null;
  try {
    return loader();
  } catch (error) {
    if (__DEV__) console.warn(\`[walkthrough] furniture model "\${key}" failed to load\`, error);
    return null;
  }
}

export default loadFurnitureModel;
`;

fs.writeFileSync(INDEX, index, "utf8");

const total = report.reduce((sum, row) => sum + row.b64, 0);
console.log(`\nwrote ${report.length} modules to ${OUTPUT_DIR}`);
console.log(`wrote ${INDEX}`);
console.log(`${(total / 1024).toFixed(1)} MB base64 total, none of it loaded until a room asks for it`);
