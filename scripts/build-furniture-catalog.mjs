/**
 * Inline the Livinai furniture catalogue (.glb) into a data module the
 * walkthrough WebView can hand straight to GLTFLoader.
 *
 * This used to bake the *geometry* out of each model into typed arrays so the
 * scene could rebuild BufferGeometry without a loader. That was smaller and
 * needed no import map, but it was not the same furniture: materials collapsed
 * to a single colour factor, any texture was dropped, and `chair-modern.glb`
 * was swapped for the dining chair to keep the bundle down.
 *
 * The models are now emitted verbatim — the exact bytes of the exact files
 * Livinai_web serves from `public/models`, decoded by the exact loader it uses.
 * Whatever a model contains (materials, textures, multiple meshes) survives.
 *
 * Run:
 *
 *     node scripts/build-furniture-catalog.mjs
 */


import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const MODELS_DIR = path.join(here, "..", "assets", "models");
const OUTPUT = path.join(here, "..", "lib", "furnitureCatalog.js");

/**
 * Catalogue key -> file, copied verbatim from Livinai_web's `MODEL_PATHS` in
 * src/Plan3DScene.jsx. Keys are `spec.model` values from the room programme.
 *
 * `workDesk` really does reuse the dining table — that is the web's own
 * mapping, not a substitution. `roundDiningTable` is deliberately null there,
 * so it has no entry here either.
 */
const CATALOG = {
  sofa: "sofa-modern.glb",
  compactSofa: "sofa-compact.glb",
  armchair: "armchair.glb",
  coffeeTable: "coffee-table.glb",
  diningTable: "dining-table.glb",
  diningChair: "dining-chair.glb",
  workDesk: "dining-table.glb",
  bed: "bed.glb",
  island: "kitchen-island.glb",
  fridge: "fridge.glb",
  vanity: "vanity.glb",
  toilet: "toilet.glb",
  shower: "shower.glb",
  bathtub: "bathtub.glb",
  tvUnit: "tv-unit.glb",
  bookcase: "bookcase.glb",
  modernChair: "chair-modern.glb",
};

/**
 * Which of those the room programme can actually reach.
 *
 * Livinai_web declares a path for `sofa`, `compactSofa`, `armchair`,
 * `coffeeTable`, `diningTable` and `bed`, but `roomFurniture` never emits those
 * model names — living rooms and bedrooms use the style-aware procedural
 * families instead. The web pays nothing for the unused entries because it
 * fetches lazily over HTTP; inlining them here would put ~4 MB of
 * `sofa-modern.glb` into the JS bundle that no scene can ever draw.
 *
 * The files stay in assets/models so the package is complete; only the bundle
 * is trimmed, and nothing that renders is affected.
 */
const REACHABLE = new Set([
  "island", "fridge", "vanity", "toilet", "shower", "bathtub",
  "diningChair", "tvUnit", "workDesk", "bookcase", "modernChair",
]);

const catalogue = {};
const report = [];
for (const [key, file] of Object.entries(CATALOG)) {
  if (!REACHABLE.has(key)) continue;
  const source = path.join(MODELS_DIR, file);
  if (!fs.existsSync(source)) {
    console.warn(`skip ${key}: ${file} not found`);
    continue;
  }
  const bytes = fs.readFileSync(source);
  if (bytes.readUInt32LE(0) !== 0x46546c67) throw new Error(`${file} is not a binary glTF`);
  catalogue[key] = bytes.toString("base64");
  report.push({ key, file, kb: bytes.length / 1024, b64: catalogue[key].length / 1024 });
}

report.sort((one, two) => two.kb - one.kb);
report.forEach((row) => console.log(
  `${row.key.padEnd(14)} ${row.file.padEnd(20)} ${row.kb.toFixed(0).padStart(6)} KB -> ${row.b64.toFixed(0).padStart(6)} KB base64`,
));

const banner = `/**
 * Generated by scripts/build-furniture-catalog.mjs — do not edit by hand.
 *
 * The Livinai furniture catalogue: the exact .glb files Livinai_web serves from
 * public/models, base64-encoded so the walkthrough WebView can parse them with
 * GLTFLoader without needing filesystem access. Bytes are untouched, so meshes,
 * materials and textures are identical to the web build.
 *
 * Keys mirror Livinai_web's MODEL_PATHS. Only the models a given plan can
 * actually use are inlined into any one scene document — see catalogFor().
 */
`;

fs.writeFileSync(
  OUTPUT,
  `${banner}\nexport const FURNITURE_CATALOG = ${JSON.stringify(catalogue)};\n\nexport default FURNITURE_CATALOG;\n`,
  "utf8",
);

const total = report.reduce((sum, row) => sum + row.b64, 0);
console.log(`\nwrote ${OUTPUT}`);
console.log(`${Object.keys(catalogue).length} models · ${(total / 1024).toFixed(1)} MB base64 total · file ${(fs.statSync(OUTPUT).size / 1024 / 1024).toFixed(1)} MB`);
