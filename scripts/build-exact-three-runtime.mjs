/** Bundle the exact Three.js runtime used by Livinai_web into the mobile app. */
import { build } from "esbuild";
import { Buffer } from "node:buffer";
import { writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(here, "..");

const result = await build({
  stdin: {
    contents: `
      import * as ThreeModule from "three";
      import { GLTFLoader } from "three/addons/loaders/GLTFLoader.js";
      import { RoomEnvironment } from "three/addons/environments/RoomEnvironment.js";
      window.THREE = { ...ThreeModule, GLTFLoader, RoomEnvironment };
    `,
    resolveDir: root,
    sourcefile: "livinai-web-three-runtime.js",
  },
  bundle: true,
  format: "iife",
  minify: true,
  target: ["chrome100", "safari15"],
  write: false,
  legalComments: "none",
});

const runtime = result.outputFiles[0].text.replace(/<\/script/gi, "<\\/script");
const output = `/* Generated by scripts/build-exact-three-runtime.mjs. */\n`
  + `export const EXACT_THREE_REVISION = "185";\n`
  + `export const EXACT_THREE_RUNTIME = ${JSON.stringify(runtime)};\n`
  + `export default EXACT_THREE_RUNTIME;\n`;

await writeFile(path.join(root, "lib", "exactThreeRuntime.js"), output, "utf8");
console.log(`Bundled Three.js r185 runtime (${Buffer.byteLength(runtime)} bytes).`);
